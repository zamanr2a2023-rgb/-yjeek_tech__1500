def dart_escape(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\n", "\\n")
        .replace("$", "\\$")
    )


def translate(english: str) -> str | None:
    if english in CURATED:
        return CURATED[english]
    # Keep codes, amounts, phones, ids, brand demos as-is
    if english.startswith("#") or english.startswith("BHD ") or english.startswith("+ BHD"):
        return english
    if english.startswith("+973"):
        return english
    if english.isdigit():
        return english
    # Already Arabic
    if any("\u0600" <= ch <= "\u06FF" for ch in english) and not any(
        "A" <= ch <= "Z" or "a" <= ch <= "z" for ch in english
    ):
        return english
    return None


def main() -> None:
    raw: dict[str, str] = json.loads(EXTRACTED.read_text(encoding="utf-8"))
    all_keys = set(raw.keys()) | set(CURATED.keys())
    entries: list[tuple[str, str]] = []
    missing: list[str] = []
    for en in sorted(all_keys, key=lambda s: s.lower()):
        ar = translate(en)
        if ar is None:
            missing.append(en)
            continue
        entries.append((en, ar))

    lines = [
        "/// English → Arabic UI strings. Keys must match English source exactly.",
        "const Map<String, String> kArabicTranslations = {",
    ]
    for en, ar in entries:
        lines.append(f"  '{dart_escape(en)}': '{dart_escape(ar)}',")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(entries)} translations ({len(missing)} pass-through) -> {OUT}")
    miss_path = ROOT / "tool" / "missing_ar.txt"
    miss_path.write_text("\n".join(missing), encoding="utf-8")
    print(f"missing listed in {miss_path} ({len(missing)})")


if __name__ == "__main__":
    main()
